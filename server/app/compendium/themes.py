SKINS: dict[str, dict[str, str]] = {
    "halloween": HALLOWEEN_SKINS,
    "nonut": NONUT_SKINS,
}


def theme_for(season: str) -> str | None:
    """Тема сезона по его ключу "YYYY-MM"."""
    try:
        return THEME_BY_MONTH.get(int(season.split("-")[1]))
    except (IndexError, ValueError):
        return None


def quest_name(q, season: str | None) -> str:
    """Название задания с учётом темы сезона."""
    theme = theme_for(season) if season else None
    if theme:
        return SKINS.get(theme, {}).get(q.id, q.name)
    return q.name


# === «Недрочабрь»: счётчик воздержания в шапке ===
# «Срыв» = катка с SLIP_DEATHS+ смертями (как порог «Курьера бронзы»).
# Счётчик «Держишься N дней» — дни по МСК с последнего срыва; без срывов в
# сезоне — с первого числа (1 ноября = 1 день). Календарь — номера дней
# месяца, в которые был срыв; клиенты рисуют крестики.
SLIP_DEATHS = 10


def abstinence_stats(rows, now: datetime | None = None) -> dict:
    """rows — строки DotaMatch ТЕКУЩЕГО сезона (ctx.rows). Чистая функция,
    тестируется без БД."""
    from app.compendium.engine import to_msk
    import calendar

    today = to_msk(now or datetime.now(timezone.utc)).date()
    slip_days = sorted({to_msk(r.started_at).date() for r in rows if r.deaths >= SLIP_DEATHS})
    slip_days = [d for d in slip_days if d.year == today.year and d.month == today.month]
    if slip_days:
        days = (today - slip_days[-1]).days
    else:
        days = today.day
    return {
        "days": max(0, days),
        "slips": [d.day for d in slip_days],
        "today": today.day,
        "days_in_month": calendar.monthrange(today.year, today.month)[1],
        "games": len(rows),
    }
